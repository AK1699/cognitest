import { Injectable, NotFoundException } from '@nestjs/common';
import { and, count, desc, eq, sql } from 'drizzle-orm';

import { AutomationStatus, AutomationTestStatus } from '@cognitest/shared';
import type {
  AutomationFramework,
  AutomationStep,
  CreateAutomationRequest,
  CreateAutomationTestRequest,
  TestStep,
  UpdateAutomationRequest,
  UpdateAutomationTestRequest,
} from '@cognitest/shared';

import { AuditService } from '../audit/audit.service';
import type { Database } from '../db/db.tokens';
import {
  automations,
  automationRuns,
  automationTests,
  testCases,
  testPlans,
  testSuites,
} from '../db/schema';
import { TenantDb } from '../db/tenant-db.service';

const ENTITY_TYPE = 'automation';
const TEST_ENTITY_TYPE = 'automation_test';

type AutomationRow = typeof automations.$inferSelect;
type AutomationTestRow = typeof automationTests.$inferSelect;

/** Turns `TC-007` → 7; anything non-conforming → 0 so it never raises the max. */
function keySuffix(key: string): number {
  const match = /(\d+)\s*$/.exec(key);
  return match ? Number.parseInt(match[1] ?? '0', 10) : 0;
}

/**
 * Builds a Playwright test stub from a case's steps. Deterministic and offline —
 * the real code generator ships with the execution runtime; this keeps the Code
 * View populated with something faithful in the meantime.
 */
function buildPlaywrightCode(
  framework: AutomationFramework,
  title: string,
  steps: TestStep[],
  baseUrl?: string,
): string {
  if (framework !== 'playwright') {
    // Other frameworks share the stub shape; only the import line differs.
    return `// ${framework} test generated by Cognitest\n// '${title}' — ${steps.length} step(s)`;
  }
  const body = steps.length
    ? steps
        .map((step) => {
          const expected = step.expected ? `  // expect: ${step.expected}` : '';
          return `  // ${step.action}${expected ? `\n${expected}` : ''}`;
        })
        .join('\n')
    : '  // no steps recorded yet';
  return [
    `import { test, expect } from '@playwright/test';`,
    ``,
    `test('${title.replace(/'/g, "\\'")}', async ({ page }) => {`,
    baseUrl ? `  await page.goto('${baseUrl}');` : `  // await page.goto(baseUrl);`,
    body,
    `});`,
    ``,
  ].join('\n');
}

@Injectable()
export class AutomationsService {
  constructor(
    private readonly tenantDb: TenantDb,
    private readonly audit: AuditService,
  ) {}

  // --------------------------------------------------------------- automations

  async list(projectId: string) {
    return this.tenantDb.run(async (tx) => {
      const rows = await tx
        .select()
        .from(automations)
        .where(eq(automations.projectId, projectId))
        .orderBy(desc(automations.createdAt));
      return Promise.all(rows.map((row) => this.withCounts(tx, row)));
    });
  }

  async create(
    projectId: string,
    organizationId: string,
    userId: string,
    input: CreateAutomationRequest,
  ) {
    return this.tenantDb.run(async (tx) => {
      const [row] = await tx
        .insert(automations)
        .values({
          projectId,
          organizationId,
          createdBy: userId,
          name: input.name,
          description: input.description ?? null,
          method: input.method ?? 'visual',
          framework: input.framework ?? 'playwright',
          tags: input.tags ?? [],
          flow: input.flow ?? [],
          config: input.config ?? {},
        })
        .returning();
      if (!row) throw new Error('automation insert returned no row');
      await this.audit.log(
        { action: 'AUTOMATION_CREATED', resourceType: ENTITY_TYPE, resourceId: row.id },
        tx,
      );
      return this.withCounts(tx, row);
    });
  }

  async getSummary(projectId: string, automationId: string) {
    return this.tenantDb.run(async (tx) => {
      const row = await this.load(tx, projectId, automationId);
      return this.withCounts(tx, row);
    });
  }

  async update(projectId: string, automationId: string, patch: UpdateAutomationRequest) {
    return this.tenantDb.run(async (tx) => {
      await this.load(tx, projectId, automationId);
      const [updated] = await tx
        .update(automations)
        .set({ ...patch, updatedAt: new Date() })
        .where(eq(automations.id, automationId))
        .returning();
      await this.audit.log(
        { action: 'AUTOMATION_UPDATED', resourceType: ENTITY_TYPE, resourceId: automationId },
        tx,
      );
      return this.withCounts(tx, updated!);
    });
  }

  /** Hard delete — composite-FK cascades remove the automation's tests and runs. */
  async remove(projectId: string, automationId: string): Promise<void> {
    await this.tenantDb.run(async (tx) => {
      await this.load(tx, projectId, automationId);
      await tx.delete(automations).where(eq(automations.id, automationId));
      await this.audit.log(
        { action: 'AUTOMATION_DELETED', resourceType: ENTITY_TYPE, resourceId: automationId },
        tx,
      );
    });
  }

  /**
   * Generates automation tests for an automation from the project's existing
   * test cases (the "From Test Cases" method). When the project has none, it
   * synthesises a single starter test from the automation's flow so the module
   * is never empty. Non-destructive: appends, skipping cases already imported.
   */
  async generate(projectId: string, organizationId: string, userId: string, automationId: string) {
    return this.tenantDb.run(async (tx) => {
      const automation = await this.load(tx, projectId, automationId);

      const projectCases = await tx
        .select({
          id: testCases.id,
          title: testCases.title,
          description: testCases.description,
          steps: testCases.steps,
          priority: testCases.priority,
        })
        .from(testCases)
        .innerJoin(testSuites, eq(testCases.testSuiteId, testSuites.id))
        .innerJoin(testPlans, eq(testSuites.testPlanId, testPlans.id))
        .where(eq(testPlans.projectId, projectId))
        .orderBy(testCases.createdAt);

      const existing = await tx
        .select({ title: automationTests.title, position: automationTests.position, key: automationTests.key })
        .from(automationTests)
        .where(eq(automationTests.automationId, automationId));
      const seen = new Set(existing.map((e) => e.title));
      let position = existing.reduce((max, e) => Math.max(max, e.position + 1), 0);
      let nextNum = existing.reduce((max, e) => Math.max(max, keySuffix(e.key)), 0);

      const source =
        projectCases.length > 0
          ? projectCases.map((c) => ({
              title: c.title,
              description: c.description,
              steps: (c.steps as TestStep[]) ?? [],
              priority: c.priority,
            }))
          : [
              {
                title: `${automation.name} — smoke test`,
                description: 'Starter test generated from the automation flow.',
                steps: (automation.flow as AutomationStep[]).map((s) => ({ action: s.label })),
                priority: 'medium' as const,
              },
            ];

      let generated = 0;
      for (const c of source) {
        if (seen.has(c.title)) continue;
        nextNum += 1;
        const key = `TC-${String(nextNum).padStart(3, '0')}`;
        await tx.insert(automationTests).values({
          organizationId,
          automationId,
          createdBy: userId,
          key,
          title: c.title,
          description: c.description ?? null,
          priority: c.priority,
          steps: c.steps,
          code: buildPlaywrightCode(
            automation.framework,
            c.title,
            c.steps,
            automation.config?.baseUrl,
          ),
          position: position++,
        });
        generated += 1;
      }

      if (automation.status === AutomationStatus.Draft && generated > 0) {
        await tx
          .update(automations)
          .set({ status: AutomationStatus.Active, updatedAt: new Date() })
          .where(eq(automations.id, automationId));
      }

      await this.audit.log(
        {
          action: 'AUTOMATION_GENERATED',
          resourceType: ENTITY_TYPE,
          resourceId: automationId,
          metadata: { generated, fromProjectCases: projectCases.length },
        },
        tx,
      );
      return { generated };
    });
  }

  // --------------------------------------------------------------------- tests

  async listTests(automationId: string) {
    return this.tenantDb.run((tx) =>
      tx
        .select()
        .from(automationTests)
        .where(eq(automationTests.automationId, automationId))
        .orderBy(automationTests.position, automationTests.createdAt),
    );
  }

  async createTest(
    automationId: string,
    organizationId: string,
    userId: string,
    input: CreateAutomationTestRequest,
  ) {
    return this.tenantDb.run(async (tx) => {
      const automation = await tx
        .select({ framework: automations.framework, baseUrl: automations.config })
        .from(automations)
        .where(eq(automations.id, automationId));
      const framework = automation[0]?.framework ?? 'playwright';
      const baseUrl = (automation[0]?.baseUrl as { baseUrl?: string } | undefined)?.baseUrl;

      const existing = await tx
        .select({ position: automationTests.position, key: automationTests.key })
        .from(automationTests)
        .where(eq(automationTests.automationId, automationId));
      const position =
        input.position ?? existing.reduce((max, e) => Math.max(max, e.position + 1), 0);
      const nextNum = existing.reduce((max, e) => Math.max(max, keySuffix(e.key)), 0) + 1;
      const key = input.key ?? `TC-${String(nextNum).padStart(3, '0')}`;
      const steps = input.steps ?? [];

      const [row] = await tx
        .insert(automationTests)
        .values({
          organizationId,
          automationId,
          createdBy: userId,
          key,
          title: input.title,
          description: input.description ?? null,
          category: input.category ?? null,
          priority: input.priority ?? 'medium',
          tags: input.tags ?? [],
          preconditions: input.preconditions ?? [],
          steps,
          expectedResult: input.expectedResult ?? null,
          code: input.code ?? buildPlaywrightCode(framework, input.title, steps, baseUrl),
          position,
        })
        .returning();
      if (!row) throw new Error('automation test insert returned no row');
      await this.audit.log(
        { action: 'AUTOMATION_TEST_CREATED', resourceType: TEST_ENTITY_TYPE, resourceId: row.id },
        tx,
      );
      return row;
    });
  }

  async getTest(automationId: string, testId: string) {
    return this.tenantDb.run((tx) => this.loadTest(tx, automationId, testId));
  }

  async updateTest(automationId: string, testId: string, patch: UpdateAutomationTestRequest) {
    return this.tenantDb.run(async (tx) => {
      await this.loadTest(tx, automationId, testId);
      // the request calls the outcome `status`; the column is `last_status`
      const { status, ...rest } = patch;
      const [updated] = await tx
        .update(automationTests)
        .set({ ...rest, ...(status ? { lastStatus: status } : {}), updatedAt: new Date() })
        .where(eq(automationTests.id, testId))
        .returning();
      await this.audit.log(
        { action: 'AUTOMATION_TEST_UPDATED', resourceType: TEST_ENTITY_TYPE, resourceId: testId },
        tx,
      );
      return updated!;
    });
  }

  async removeTest(automationId: string, testId: string): Promise<void> {
    await this.tenantDb.run(async (tx) => {
      await this.loadTest(tx, automationId, testId);
      await tx.delete(automationTests).where(eq(automationTests.id, testId));
      await this.audit.log(
        { action: 'AUTOMATION_TEST_DELETED', resourceType: TEST_ENTITY_TYPE, resourceId: testId },
        tx,
      );
    });
  }

  /** Confirms an automation is in the project; used before nesting child routes. */
  async assertInProject(projectId: string, automationId: string): Promise<void> {
    await this.tenantDb.run((tx) => this.load(tx, projectId, automationId));
  }

  // ------------------------------------------------------------------ helpers

  private async load(
    tx: Database,
    projectId: string,
    automationId: string,
  ): Promise<AutomationRow> {
    const [row] = await tx
      .select()
      .from(automations)
      .where(and(eq(automations.id, automationId), eq(automations.projectId, projectId)));
    if (!row) throw new NotFoundException();
    return row;
  }

  private async loadTest(
    tx: Database,
    automationId: string,
    testId: string,
  ): Promise<AutomationTestRow> {
    const [row] = await tx
      .select()
      .from(automationTests)
      .where(and(eq(automationTests.id, testId), eq(automationTests.automationId, automationId)));
    if (!row) throw new NotFoundException();
    return row;
  }

  private async withCounts(tx: Database, automation: AutomationRow) {
    const [counts] = await tx
      .select({
        total: count(),
        passed: sql<number>`count(*) filter (where ${automationTests.lastStatus} = ${AutomationTestStatus.Passed})`.mapWith(
          Number,
        ),
        failed: sql<number>`count(*) filter (where ${automationTests.lastStatus} = ${AutomationTestStatus.Failed})`.mapWith(
          Number,
        ),
      })
      .from(automationTests)
      .where(eq(automationTests.automationId, automation.id));
    const [lastRun] = await tx
      .select({ status: automationRuns.status, createdAt: automationRuns.createdAt })
      .from(automationRuns)
      .where(eq(automationRuns.automationId, automation.id))
      .orderBy(desc(automationRuns.createdAt))
      .limit(1);
    return {
      ...automation,
      testCount: counts?.total ?? 0,
      passedCount: counts?.passed ?? 0,
      failedCount: counts?.failed ?? 0,
      lastRunStatus: lastRun?.status ?? null,
      lastRunAt: lastRun?.createdAt ?? null,
    };
  }
}
